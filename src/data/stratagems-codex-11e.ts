/**
 * Detachment stratagems from the 11th Edition codexes, read from the codex
 * faction pages Mark saved from Wahapedia on 8 Nov 2026 (codex app data,
 * October 2026). See CODEX_SOURCES in stratagem-sources.ts.
 *
 * Names, CP costs, phases and timing are recorded as facts. Effects are written
 * in our own words: the pages reproduce paid codex text, so nothing here is
 * copied from them. 11e codexes print no Battle Tactic/Strategic Ploy subtype,
 * so every entry has type "detachment". Boarding Actions detachments are left
 * out, as elsewhere in stratagems.ts.
 */
import type { Stratagem } from "../types.js";

type Entry = [name: string, cpCost: number, phase: string, when: string, target: string, effect: string, restrictions?: string];

function detachment(faction: string, detachmentName: string, entries: Entry[]): Stratagem[] {
  return entries.map(([name, cpCost, phase, when, target, effect, restrictions]) => ({
    name,
    faction,
    detachment: detachmentName,
    type: "detachment" as const,
    cpCost,
    phase,
    when,
    target,
    effect,
    ...(restrictions ? { restrictions } : {}),
    gameModes: ["40k" as const],
  }));
}

/** "Roll to keep fighting" effect shared by several codex stratagems. */
function fightOnDeath(threshold: string, bonus: string): string {
  return `Each time a model in your unit is destroyed while your unit has not yet been selected to fight this phase, roll a D6${bonus}. On a ${threshold}, leave the model on the battlefield; it is removed once your unit has fought or at the end of the phase, whichever comes first.`;
}

